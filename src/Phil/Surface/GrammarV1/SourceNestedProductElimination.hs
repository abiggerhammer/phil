-- | FSEM-01 DATA-05C: bounded, source-owned nested product elaboration.
--
-- This is an opt-in Grammar-v1 route for two mirrored two-level product
-- patterns with intrinsic Bool, Bytes[8] and Unit leaves. It derives both
-- qualified Surface product contracts from rechecked original source, rather
-- than accepting a caller-authored plan or an environment with trusted
-- product expectations. It does not change general type checking.
