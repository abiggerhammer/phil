data GrammarV1NestedProductError
  = NestedProductParameterError GrammarV1BinderScopeError
  | NestedProductLetError GrammarV1LetPatternScopeError
  | NestedProductLeafTypeError FocusingError
  | NestedProductSourceMismatch Text
  | NestedProductSurfaceError SurfaceCheckError
  | NestedProductTransitionMismatch Text
  deriving (Eq, Show)

-- | The accepted result carries exact real production Surface observations.
-- The intermediate is generated by this source-owned adapter, not a binder
-- in the original Grammar-v1 AST. No independent environment is a parameter.
data GrammarV1NestedProductTrace = GrammarV1NestedProductTrace
  { nestedProductDeclarationKey :: DeclarationKey
  , nestedProductOriginalOwner :: GrammarV1ResolvedBinder
  , nestedProductOriginalLeaves :: [GrammarV1ResolvedBinder]
  , nestedProductInternalOwner :: Name
  , nestedProductOuterContract :: [ProductElementType]
  , nestedProductInnerContract :: [ProductElementType]
  , nestedProductDeclaredReturn :: CheckedTypeMode
  , nestedProductFirstCut :: ProductEliminationRun
  , nestedProductSecondCut :: ProductEliminationRun
  , nestedProductAccepted :: SurfaceCheckResult
  }
  deriving (Eq, Show)

data Side = InnerLeft | InnerRight deriving (Eq, Show)

bytes8 :: Ty
bytes8 = TyBytes (RefNat 8)

innerMembers :: [ProductElementType]
innerMembers =
  [ ProductElementType Linear bytes8
  , ProductElementType Unrestricted TyUnit ]

innerTy :: Ty
innerTy = TyProduct innerMembers

outerMembers :: Side -> [ProductElementType]
outerMembers InnerLeft =
  [ ProductElementType Linear innerTy
  , ProductElementType Unrestricted TyBool ]
outerMembers InnerRight =
  [ ProductElementType Unrestricted TyBool
  , ProductElementType Linear innerTy ]

isSourceName :: Located GrammarV1Pattern -> Bool
isSourceName (Located _ (GrammarV1IdentifierPattern _)) = True
isSourceName _ = False

twoNames :: Located GrammarV1Pattern -> Bool
twoNames (Located _ (GrammarV1TuplePattern [a,b])) =
  isSourceName a && isSourceName b
twoNames _ = False

sourcePatternSide
  :: Located GrammarV1Pattern -> Maybe (Side, SourceSpan)
sourcePatternSide (Located _ (GrammarV1TuplePattern [a,b]))
  | isSourceName a && twoNames b = Just (InnerRight, locatedSpan b)
  | twoNames a && isSourceName b = Just (InnerLeft, locatedSpan a)
sourcePatternSide _ = Nothing

binderName :: GrammarV1ResolvedBinder -> Name
binderName = grammarV1ResolvedBinderCoreName

sameBinder :: GrammarV1ResolvedBinder -> GrammarV1ResolvedBinder -> Bool
sameBinder a b = grammarV1ResolvedBinderKey a == grammarV1ResolvedBinderKey b

-- | Finite test-established source fragment promoted into an *opt-in*
-- production source adapter. Every primitive leaf is checked with the
-- existing checker; recursive assembly is allowed only for pairs, and the
-- exact expected two-level product is validated before any Surface call.
checkedPair
  :: StaticContext
  -> Located GrammarV1Type
  -> Maybe (Either FocusingError CheckedTypeMode)
checkedPair static (Located _ sourceType) = case sourceType of
  GrammarV1TupleType [a,b] -> do
    left <- checkedPair static a
    right <- checkedPair static b
    pure $ do
      a' <- left
      b' <- right
      let elements =
            [ ProductElementType (checkedBindingMode ty)
                (checkedBindingType ty)
            | ty <- [a',b'] ]
      pure (CheckedTypeMode
        (TyProduct elements) (ProductMode.productMode elements))
  GrammarV1TupleType _ -> Nothing
  GrammarV1BoolType -> checkedPrimitive
  GrammarV1UnitType -> checkedPrimitive
  GrammarV1BytesType _ -> checkedPrimitive
  -- Aliases, refinements, proof-carrying and unrelated named forms stay out.
  _ -> Nothing
  where
    checkedPrimitive = do
      checked <- grammarV1CheckedTypeMode static emptySurfaceState sourceType
      pure (fst <$> checked)

namePattern :: SourceSpan -> Name -> Located Pattern
namePattern span' owner = Located span' (BindPattern (unName owner))

flatLet :: SourceSpan -> Name -> [Name] -> Located Statement
flatLet span' source destinations =
  Located span' (LetStatement
    (Located span' (TuplePattern (map (namePattern span') destinations)))
    (Located span' (VariableExpression (unName source))))

flatReturn :: SourceSpan -> Name -> Located Statement
flatReturn span' source =
  Located span' (ReturnStatement
    (Located span' (VariableExpression (unName source))))

component
  :: Text -> SourceSpan -> [Located Statement] -> Located Component
component sourceName span' statements = Located span' (Component
  { componentName = sourceName
  , componentParameters = []
  , componentProvides = Nothing
  , componentBody = Located span' (Block statements)
  })

initialBinding :: Mode -> Ty -> InitialBinding
initialBinding mode ty = InitialBinding mode ty (shapeForType ty)

failShape :: Text -> Either GrammarV1NestedProductError a
failShape = Left . NestedProductSourceMismatch

-- | The normal production Surface transitions are reached only after both
-- semantic owner identities, the two-level pattern and each checked source
-- type/mode match. No caller-supplied product contract is accepted.
grammarV1CheckedNestedProductElimination
  :: StaticContext
  -> DeclarationKey
  -> GrammarV1FunctionDecl
  -> Maybe (Either GrammarV1NestedProductError GrammarV1NestedProductTrace)
grammarV1CheckedNestedProductElimination static declarationKey source
  | grammarV1FunctionRecursive source = Nothing
  | not (null (grammarV1FunctionGenericParams source)) = Nothing
  | not (null (grammarV1FunctionRequirements source)) = Nothing
  | otherwise = do
      [Located _ parameter] <- pure (grammarV1FunctionTermParams source)
      declaredResult <- grammarV1FunctionResultType source
      [Located letSpan (GrammarV1LetStatement patternSource _),
       Located returnSpan (GrammarV1ReturnStatement _)] <-
        pure (grammarV1BlockStatements
          (locatedValue (grammarV1FunctionBody source)))
      (side, nestedSpan) <- sourcePatternSide patternSource
      -- An unresolved source occurrence can denote a static/global name;
      -- the bounded lexical route must report noncompetence, not an
      -- authoritative invalid-program judgment. Keep this outside Either.
      case grammarV1FunctionParameterScope declarationKey source of
        Right (_, parameterScope) ->
          case grammarV1CheckedLetPatternBlockInScope parameterScope
              (grammarV1FunctionBody source) of
            Nothing -> Nothing
            _ -> Just ()
        Left _ -> Just ()
      typedInput <- checkedPair static (grammarV1TermParamType parameter)
      typedResult <- checkedPair static declaredResult
      case (typedInput, typedResult) of
        (Left err, _) -> Just (Left (NestedProductLeafTypeError err))
        (_, Left err) -> Just (Left (NestedProductLeafTypeError err))
        (Right packetType, Right resultType) ->
          Just $ do
            (owner, patternBinders, flagBinder, payloadBinder, spareBinder) <-
              case grammarV1FunctionParameterScope declarationKey source of
                Left err -> Left (NestedProductParameterError err)
                Right ([ownerBinder], initialScope) ->
                  case grammarV1CheckedLetPatternBlockInScope initialScope
                      (grammarV1FunctionBody source) of
                    Nothing -> failShape "source let/return lexical fragment is unsupported"
                    Just (Left err) -> Left (NestedProductLetError err)
                    Just (Right
                      ([GrammarV1CheckedLetBindingStep _ input binders,
                        GrammarV1CheckedLetOccurrenceStep _ returned],_)) ->
                      let initializerBinder = grammarV1CheckedLocalValueBinder input
                          returnedBinder = grammarV1CheckedLocalValueBinder returned
                          ordered = case (side,binders) of
                            (InnerRight,[a,b,c]) -> Just (a,b,c)
                            (InnerLeft,[a,b,c]) -> Just (c,a,b)
                            _ -> Nothing
                      in case ordered of
                        Nothing -> failShape "nested let must restore three leaf binders"
                        Just (flagLeaf,payloadLeaf,spareLeaf)
                          | not (sameBinder initializerBinder ownerBinder) ->
                              failShape "nested initializer is not the checked parameter owner"
                          | not (sameBinder returnedBinder payloadLeaf) ->
                              failShape "returned source occurrence is not the checked Bytes leaf"
                          | otherwise ->
                              Right (ownerBinder,binders,
                                flagLeaf,payloadLeaf,spareLeaf)
                    Just (Right _) ->
                      failShape "unsupported nested lexical sequence"
                Right _ -> failShape "one checked function parameter required"

            if packetType /= CheckedTypeMode
                 (TyProduct (outerMembers side)) Linear
              then failShape "nested product source element types or modes differ"
              else Right ()
            if resultType /= CheckedTypeMode bytes8 Linear
              then failShape "nested source return must be Linear Bytes[8]"
              else Right ()

            let packet = binderName owner
                flag = binderName flagBinder
                payload = binderName payloadBinder
                spare = binderName spareBinder
                mid = Name ("$phil.data05c.inner:" <> unName packet)
                sourceNames = [packet,flag,payload,spare,mid]
            if Set.size (Set.fromList sourceNames) /= 5
              then failShape "source-rooted owners collide with generated Core owner"
              else Right ()

            let outer = outerMembers side
                firstDest = case side of
                  InnerLeft -> [mid,flag]
                  InnerRight -> [flag,mid]
                secondDest = [payload,spare]
                firstLet = flatLet letSpan packet firstDest
                secondLet = flatLet nestedSpan mid secondDest
                returnActual = flatReturn returnSpan payload
                firstComponent = component
                  (locatedValue (grammarV1FunctionName source)) letSpan
                  [firstLet, flatReturn returnSpan flag]
                secondComponent = component
                  (locatedValue (grammarV1FunctionName source)) letSpan
                  [secondLet,returnActual]
                completeComponent = component
                  (locatedValue (grammarV1FunctionName source)) letSpan
                  [firstLet,secondLet,returnActual]
                qualified = Map.fromList
                  [(unName packet,outer),(unName mid,innerMembers)]
                baseEnvironment = (emptySurfaceEnvironment static)
                  { surfaceInitialBindings = Map.singleton
                      (unName packet)
                      (initialBinding Linear (checkedBindingType packetType))
                  , surfaceExpectedProductEliminations = qualified }
                intermediateEnvironment = baseEnvironment
                  { surfaceInitialBindings = Map.fromList
                      [ (unName flag,initialBinding Unrestricted TyBool)
                      , (unName mid,initialBinding Linear innerTy) ] }
                expectedInitial = Core.ResourceContext Map.empty Map.empty
                  (Map.singleton packet (checkedBindingType packetType)) Set.empty
                expectedOuter = Core.ResourceContext
                  (Map.singleton flag TyBool) Map.empty
                  (Map.singleton mid innerTy) Set.empty
                expectedInner = Core.ResourceContext
                  (Map.fromList [(flag,TyBool),(spare,TyUnit)]) Map.empty
                  (Map.singleton payload bytes8) Set.empty
                firstResult = checkSurfaceComponent baseEnvironment firstComponent
                secondResult = checkSurfaceComponent
                  intermediateEnvironment secondComponent
                completeResult = checkSurfaceComponent
                  baseEnvironment completeComponent
                expectedResult = SurfaceCheckResult
                  (locatedValue (grammarV1FunctionName source))
                  [Return bytes8]

            firstCut <- case traceSurfaceProductEliminationComponent
                baseEnvironment firstComponent of
              Just trace -> Right trace
              Nothing -> Left (NestedProductTransitionMismatch
                "original-source outer product has no actual Surface trace")
            secondCut <- case traceSurfaceProductEliminationComponent
                intermediateEnvironment secondComponent of
              Just trace -> Right trace
              Nothing -> Left (NestedProductTransitionMismatch
                "original-source inner product has no actual Surface trace")
            if productEliminationBefore firstCut /= Just expectedInitial ||
               productEliminationAfter firstCut /= Just expectedOuter
              then Left (NestedProductTransitionMismatch
                "actual first Surface predecessor/successor differs from checked source")
              else Right ()
            if productEliminationBefore secondCut /= Just expectedOuter ||
               productEliminationAfter secondCut /= Just expectedInner
              then Left (NestedProductTransitionMismatch
                "actual second Surface predecessor/successor differs from checked source")
              else Right ()
            case firstResult of
              Left err | surfaceErrorClass err == LinearCompletion -> Right ()
              Left err -> Left (NestedProductSurfaceError err)
              Right _ -> Left (NestedProductTransitionMismatch
                "partial outer product permitted a live Linear inner owner to escape")
            case secondResult of
              Left err -> Left (NestedProductSurfaceError err)
              Right accepted
                | accepted == expectedResult -> Right ()
                | otherwise -> Left (NestedProductTransitionMismatch
                    "second Surface return differs from source checked Bytes result")
            case completeResult of
              Left err -> Left (NestedProductSurfaceError err)
              Right accepted
                | accepted /= expectedResult ||
                  productEliminationOutcome firstCut /= firstResult ||
                  productEliminationOutcome secondCut /= secondResult ->
                    Left (NestedProductTransitionMismatch
                      "full Surface return or source prefix observations diverged")
                | otherwise -> Right GrammarV1NestedProductTrace
                    { nestedProductDeclarationKey = declarationKey
                    , nestedProductOriginalOwner = owner
                    , nestedProductOriginalLeaves = patternBinders
                    , nestedProductInternalOwner = mid
                    , nestedProductOuterContract = outer
                    , nestedProductInnerContract = innerMembers
                    , nestedProductDeclaredReturn = resultType
                    , nestedProductFirstCut = firstCut
                    , nestedProductSecondCut = secondCut
                    , nestedProductAccepted = accepted
                    }


-- DATA-04/05D: opt-in three-level nested pair from one original source AST.
-- DATA-05C's two-level entry point remains unchanged and independent.
data GrammarV1ThreeLevelProductTrace = GrammarV1ThreeLevelProductTrace
  { threeLevelDeclarationKey :: DeclarationKey
  , threeLevelOriginalOwner :: GrammarV1ResolvedBinder
  , threeLevelOriginalLeaves :: [GrammarV1ResolvedBinder]
  , threeLevelMiddleOwner :: Name
  , threeLevelDeepOwner :: Name
  , threeLevelOuterContract :: [ProductElementType]
  , threeLevelMiddleContract :: [ProductElementType]
  , threeLevelDeepContract :: [ProductElementType]
  , threeLevelDeclaredReturn :: CheckedTypeMode
  , threeLevelFirstCut :: ProductEliminationRun
  , threeLevelSecondCut :: ProductEliminationRun
  , threeLevelThirdCut :: ProductEliminationRun
  , threeLevelAccepted :: SurfaceCheckResult
  }
  deriving (Eq, Show)

threeLevelPatternSpans
  :: Located GrammarV1Pattern -> Maybe (SourceSpan, SourceSpan)
threeLevelPatternSpans
    (Located _ (GrammarV1TuplePattern [flag, middle])) =
  case middle of
    Located middleSpan (GrammarV1TuplePattern [before, deep]) ->
      case deep of
        Located deepSpan (GrammarV1TuplePattern [payload, after])
          | all isSourceName [flag,before,payload,after] ->
              Just (middleSpan, deepSpan)
        _ -> Nothing
    _ -> Nothing
threeLevelPatternSpans _ = Nothing

threeLevelDeepElements :: [ProductElementType]
threeLevelDeepElements =
  [ ProductElementType Linear bytes8
  , ProductElementType Unrestricted TyUnit ]

threeLevelDeepTy :: Ty
threeLevelDeepTy = TyProduct threeLevelDeepElements

threeLevelMiddleElements :: [ProductElementType]
threeLevelMiddleElements =
  [ ProductElementType Unrestricted TyUnit
  , ProductElementType Linear threeLevelDeepTy ]

threeLevelMiddleTy :: Ty
threeLevelMiddleTy = TyProduct threeLevelMiddleElements

threeLevelOuterElements :: [ProductElementType]
threeLevelOuterElements =
  [ ProductElementType Unrestricted TyBool
  , ProductElementType Linear threeLevelMiddleTy ]

-- Only checked original source and its declaration root may supply authority.
-- Caller-provided Surface environments, contracts or synthetic owner names
-- are impossible inputs. Unsupported source forms remain noncompetence.
grammarV1CheckedThreeLevelProductElimination
  :: StaticContext
  -> DeclarationKey
  -> GrammarV1FunctionDecl
  -> Maybe (Either GrammarV1NestedProductError GrammarV1ThreeLevelProductTrace)
grammarV1CheckedThreeLevelProductElimination static declarationKey source
  | grammarV1FunctionRecursive source = Nothing
  | not (null (grammarV1FunctionGenericParams source)) = Nothing
  | not (null (grammarV1FunctionRequirements source)) = Nothing
  | otherwise = do
      [Located _ parameter] <- pure (grammarV1FunctionTermParams source)
      declaredResult <- grammarV1FunctionResultType source
      [Located letSpan (GrammarV1LetStatement sourcePattern _),
       Located returnSpan (GrammarV1ReturnStatement _)] <-
        pure (grammarV1BlockStatements
          (locatedValue (grammarV1FunctionBody source)))
      (middleSpan,deepSpan) <- threeLevelPatternSpans sourcePattern
      -- An unresolved local could mean a static/global value, not invalid
      -- language. Preserve DATA-05C's noncompetence boundary.
      case grammarV1FunctionParameterScope declarationKey source of
        Right (_, parameterScope) ->
          case grammarV1CheckedLetPatternBlockInScope parameterScope
              (grammarV1FunctionBody source) of
            Nothing -> Nothing
            _ -> Just ()
        Left _ -> Just ()
      typedInput <- checkedPair static (grammarV1TermParamType parameter)
      typedResult <- checkedPair static declaredResult
      case (typedInput,typedResult) of
        (Left err,_) -> Just (Left (NestedProductLeafTypeError err))
        (_,Left err) -> Just (Left (NestedProductLeafTypeError err))
        (Right inputType,Right resultType) ->
          Just $ do
            (owner,leaves,flagBinder,beforeBinder,payloadBinder,afterBinder) <-
              case grammarV1FunctionParameterScope declarationKey source of
                Left err -> Left (NestedProductParameterError err)
                Right ([ownerBinder],initialScope) ->
                  case grammarV1CheckedLetPatternBlockInScope initialScope
                      (grammarV1FunctionBody source) of
                    Nothing -> failShape "three-level lexical source is unsupported"
                    Just (Left err) -> Left (NestedProductLetError err)
                    Just (Right
                      ([GrammarV1CheckedLetBindingStep _ input binders,
                        GrammarV1CheckedLetOccurrenceStep _ returned],_)) ->
                      case binders of
                        [flagLeaf,beforeLeaf,payloadLeaf,afterLeaf]
                          | not (sameBinder
                              (grammarV1CheckedLocalValueBinder input)
                              ownerBinder) ->
                              failShape "three-level initializer differs from checked source owner"
                          | not (sameBinder
                              (grammarV1CheckedLocalValueBinder returned)
                              payloadLeaf) ->
                              failShape "three-level returned source occurrence differs from Bytes leaf"
                          | otherwise ->
                              Right (ownerBinder,binders,flagLeaf,beforeLeaf,
                                payloadLeaf,afterLeaf)
                        _ -> failShape "three-level source needs four exact leaves"
                    Just (Right _) -> failShape "unsupported three-level lexical sequence"
                Right _ -> failShape "one checked source parameter required"
            if inputType /= CheckedTypeMode
                (TyProduct threeLevelOuterElements) Linear
              then failShape "three-level source product element types or modes differ"
              else Right ()
            if resultType /= CheckedTypeMode bytes8 Linear
              then failShape "three-level declared return must be Linear Bytes[8]"
              else Right ()
            let packet = binderName owner
                flag = binderName flagBinder
                before = binderName beforeBinder
                payload = binderName payloadBinder
                after = binderName afterBinder
                middle = Name ("$phil.data05d.middle:" <> unName packet)
                deep = Name ("$phil.data05d.deep:" <> unName packet)
                sourceNames = [packet,flag,before,payload,after,middle,deep]
            if Set.size (Set.fromList sourceNames) /= length sourceNames
              then failShape "three-level source/Core owner identities collide"
              else Right ()
            let firstLet = flatLet letSpan packet [flag,middle]
                secondLet = flatLet middleSpan middle [before,deep]
                thirdLet = flatLet deepSpan deep [payload,after]
                finalReturn = flatReturn returnSpan payload
                sourceName = locatedValue (grammarV1FunctionName source)
                qualified = Map.fromList
                  [ (unName packet,threeLevelOuterElements)
                  , (unName middle,threeLevelMiddleElements)
                  , (unName deep,threeLevelDeepElements) ]
                initialEnv = (emptySurfaceEnvironment static)
                  { surfaceInitialBindings = Map.singleton
                      (unName packet)
                      (initialBinding Linear (checkedBindingType inputType))
                  , surfaceExpectedProductEliminations = qualified }
                middleEnv = initialEnv
                  { surfaceInitialBindings = Map.fromList
                      [ (unName flag,initialBinding Unrestricted TyBool)
                      , (unName middle,initialBinding Linear threeLevelMiddleTy) ] }
                deepEnv = initialEnv
                  { surfaceInitialBindings = Map.fromList
                      [ (unName flag,initialBinding Unrestricted TyBool)
                      , (unName before,initialBinding Unrestricted TyUnit)
                      , (unName deep,initialBinding Linear threeLevelDeepTy) ] }
                context0 = Core.ResourceContext Map.empty Map.empty
                  (Map.singleton packet (checkedBindingType inputType)) Set.empty
                context1 = Core.ResourceContext
                  (Map.singleton flag TyBool) Map.empty
                  (Map.singleton middle threeLevelMiddleTy) Set.empty
                context2 = Core.ResourceContext
                  (Map.fromList [(flag,TyBool),(before,TyUnit)]) Map.empty
                  (Map.singleton deep threeLevelDeepTy) Set.empty
                context3 = Core.ResourceContext
                  (Map.fromList [(flag,TyBool),(before,TyUnit),(after,TyUnit)])
                  Map.empty (Map.singleton payload bytes8) Set.empty
                firstPart = component sourceName letSpan
                  [firstLet,flatReturn returnSpan flag]
                secondPart = component sourceName letSpan
                  [secondLet,flatReturn returnSpan before]
                thirdPart = component sourceName letSpan
                  [thirdLet,finalReturn]
                fullPart = component sourceName letSpan
                  [firstLet,secondLet,thirdLet,finalReturn]
                firstResult = checkSurfaceComponent initialEnv firstPart
                secondResult = checkSurfaceComponent middleEnv secondPart
                thirdResult = checkSurfaceComponent deepEnv thirdPart
                fullResult = checkSurfaceComponent initialEnv fullPart
                expected = SurfaceCheckResult sourceName [Return bytes8]
            firstCut <- case traceSurfaceProductEliminationComponent
                initialEnv firstPart of
              Just cut -> Right cut
              Nothing -> Left (NestedProductTransitionMismatch
                "source-derived outer product had no actual Surface cut")
            secondCut <- case traceSurfaceProductEliminationComponent
                middleEnv secondPart of
              Just cut -> Right cut
              Nothing -> Left (NestedProductTransitionMismatch
                "source-derived middle product had no actual Surface cut")
            thirdCut <- case traceSurfaceProductEliminationComponent
                deepEnv thirdPart of
              Just cut -> Right cut
              Nothing -> Left (NestedProductTransitionMismatch
                "source-derived deep product had no actual Surface cut")
            if productEliminationBefore firstCut /= Just context0 ||
               productEliminationAfter firstCut /= Just context1 ||
               productEliminationBefore secondCut /= Just context1 ||
               productEliminationAfter secondCut /= Just context2 ||
               productEliminationBefore thirdCut /= Just context2 ||
               productEliminationAfter thirdCut /= Just context3
              then Left (NestedProductTransitionMismatch
                "actual ordered production cuts differ from original-source Core states")
              else Right ()
            case firstResult of
              Left err | surfaceErrorClass err == LinearCompletion -> Right ()
              Left err -> Left (NestedProductSurfaceError err)
              Right _ -> Left (NestedProductTransitionMismatch
                "first partial return hid a live Linear intermediate")
            case secondResult of
              Left err | surfaceErrorClass err == LinearCompletion -> Right ()
              Left err -> Left (NestedProductSurfaceError err)
              Right _ -> Left (NestedProductTransitionMismatch
                "second partial return hid a live Linear intermediate")
            case thirdResult of
              Right result | result == expected -> Right ()
              Left err -> Left (NestedProductSurfaceError err)
              _ -> Left (NestedProductTransitionMismatch
                "third-stage return was not exactly Linear Bytes[8]")
            case fullResult of
              Right result
                | result == expected &&
                  productEliminationOutcome firstCut == firstResult &&
                  productEliminationOutcome secondCut == secondResult &&
                  productEliminationOutcome thirdCut == thirdResult ->
                    Right GrammarV1ThreeLevelProductTrace
                      { threeLevelDeclarationKey = declarationKey
                      , threeLevelOriginalOwner = owner
                      , threeLevelOriginalLeaves = leaves
                      , threeLevelMiddleOwner = middle
                      , threeLevelDeepOwner = deep
                      , threeLevelOuterContract = threeLevelOuterElements
                      , threeLevelMiddleContract = threeLevelMiddleElements
                      , threeLevelDeepContract = threeLevelDeepElements
                      , threeLevelDeclaredReturn = resultType
                      , threeLevelFirstCut = firstCut
                      , threeLevelSecondCut = secondCut
                      , threeLevelThirdCut = thirdCut
                      , threeLevelAccepted = result
                      }
              Left err -> Left (NestedProductSurfaceError err)
              _ -> Left (NestedProductTransitionMismatch
                "full three-level Surface run diverged from source-owned plan")
