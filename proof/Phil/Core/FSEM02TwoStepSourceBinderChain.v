(* Bounded production-component binder gate: these are implications about
   resolved identity equality under an explicit freshness premise, NOT a
   theorem that the Haskell binder resolver or the full source compiler
   implements this model. *)
Theorem fsem02SourceSecondPredecessorStaleIsNotFresh :
  forall (original successor second : Name),
    original <> successor ->
    second = original ->
    second <> successor.
Proof.
  intros original successor second Hfresh Hstale.
  congruence.
Qed.

Theorem fsem02SourceSecondPredecessorFreshIsNotStale :
  forall (original successor second : Name),
    original <> successor ->
    second = successor ->
    second <> original.
Proof.
  intros original successor second Hfresh Hnext.
  congruence.
Qed.

(* The bounded Send payload gate compares actual post-let occurrence identity
   with externally supplied parameter identity. This lemma only states the
   consequence of explicit freshness and selected-identity premises; it does
   not prove Haskell lexical resolution or payload typing. *)
Theorem fsem02LaterBoundPayloadNotOriginalParameter :
  forall (originalParameter laterBinder resolved : Name),
    originalParameter <> laterBinder ->
    resolved = laterBinder ->
    resolved <> originalParameter.
Proof.
  intros originalParameter laterBinder resolved Hfresh Hresolved.
  congruence.
Qed.
Print Assumptions fsem02LaterBoundPayloadNotOriginalParameter.

(* This is a finite U8 witness-envelope classifier, not the source type AST
   or an implementation-refinement theorem. Every other written annotation
   belongs to Other; the expected U8 protocol head is supplied externally. *)
Inductive FSEM02WrittenReceiveType : Type :=
| FSEM02WrittenU8
| FSEM02WrittenOther.

Definition fsem02TwoReceiveU8WitnessGate
    (first second : FSEM02WrittenReceiveType) : bool :=
  match first, second with
  | FSEM02WrittenU8, FSEM02WrittenU8 => true
  | _, _ => false
  end.

Theorem fsem02TwoReceiveU8WitnessGateSound :
  forall first second,
    fsem02TwoReceiveU8WitnessGate first second = true ->
    first = FSEM02WrittenU8 /\ second = FSEM02WrittenU8.
Proof.
  intros first second Hgate.
  destruct first, second; simpl in Hgate; try discriminate;
    split; reflexivity.
Qed.
Print Assumptions fsem02TwoReceiveU8WitnessGateSound.

(* The options model primitive elaboration at the two resolved binder
   identities. The external projection premise supplies the abstract U8
   carrier. The model does not establish either producer's fidelity. *)
Definition fsem02SendU8Parameter (width : option nat) : bool :=
  match width with
  | Some n => Nat.eqb n 8
  | None => false
  end.

Definition fsem02TwoSendU8ParameterGate (first second : option nat) : bool :=
  andb (fsem02SendU8Parameter first) (fsem02SendU8Parameter second).

Theorem fsem02TwoSendU8ParameterGateSound :
  forall first second,
    fsem02TwoSendU8ParameterGate first second = true ->
    first = Some 8 /\ second = Some 8.
Proof.
  intros first second H.
  unfold fsem02TwoSendU8ParameterGate in H.
  apply Bool.andb_true_iff in H as [Hfirst Hsecond].
  split.
  - destruct first as [width |]; try discriminate.
    change (Nat.eqb width 8 = true) in Hfirst.
    now apply Nat.eqb_eq in Hfirst; subst.
  - destruct second as [width |]; try discriminate.
    change (Nat.eqb width 8 = true) in Hsecond.
    now apply Nat.eqb_eq in Hsecond; subst.
Qed.
Print Assumptions fsem02TwoSendU8ParameterGateSound.

(* The model receives resolved projection evidence independently. Name stands
   for an already-resolved revision or role identity. The resolver and native
   equality implementation are outside this statement. *)
Definition fsem02ExactEndpointProjection
    (actual expected : (Name * Name * Session)%type) : Prop :=
  actual = expected.

Theorem fsem02ExactSendProjectionRejectsDifferentRevision :
  forall actualRevision expectedRevision role session,
    actualRevision <> expectedRevision ->
    ~ fsem02ExactEndpointProjection
        (actualRevision, role, session) (expectedRevision, role, session).
Proof.
  unfold fsem02ExactEndpointProjection.
  intros actualRevision expectedRevision role session Hrevision Hequal.
  now inversion Hequal.
Qed.
Print Assumptions fsem02ExactSendProjectionRejectsDifferentRevision.

Theorem fsem02ExactReceiveProjectionRejectsDifferentRole :
  forall revision actualRole expectedRole actualSession expectedSession,
    actualRole <> expectedRole ->
    ~ fsem02ExactEndpointProjection
        (revision, actualRole, actualSession) (revision, expectedRole, expectedSession).
Proof.
  unfold fsem02ExactEndpointProjection.
  intros revision actualRole expectedRole actualSession expectedSession Hrole Hequal.
  now inversion Hequal.
Qed.
Print Assumptions fsem02ExactReceiveProjectionRejectsDifferentRole.
